_LANG = "zh"


def init_lang():
    global _LANG
    env = os.environ.get("OSD_LANG", "").strip().lower()
    if env in ("en", "zh"):
        _LANG = env
        return
    try:
        p = os.path.join(base_dir(), "lang.txt")
        if os.path.exists(p):
            v = open(p, encoding="utf-8").read().strip().lower()
            if v in ("en", "zh"):
                _LANG = v
    except Exception:
        pass


def t(key, **kw):
    table = _EN if _LANG == "en" else _ZH
    s = table.get(key, key)
    if kw:
        s = s % kw
    return s


def lang():
    return _LANG


init_lang()
